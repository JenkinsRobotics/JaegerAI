import {act} from 'react';
import {createRoot} from 'react-dom/client';
import {afterEach, expect, it, vi} from 'vitest';
import {WebhooksPanel} from './WebhooksPanel';
import type {JaegerSource, WebhookDefinition, WebhookSubscription} from '../api/source';
import type {Agent} from '../api/types';
(globalThis as {IS_REACT_ACT_ENVIRONMENT?: boolean}).IS_REACT_ACT_ENVIRONMENT = true;
const prefix = 'jaeger.ui.webhook.';
afterEach(() => {for (const key of Object.keys(localStorage)) if (key.startsWith(prefix)) localStorage.removeItem(key);});
const def: WebhookDefinition = {name: 'Owned webhook', provider: 'generic', events: ['changed'], senders: ['owner-fixture'], session_id: 'home-owned', objective: 'Review fixture event', enabled: false, archived: false};
const row: WebhookSubscription = {...def, id: 'owned-sub', agent_id: 'owned-bot', revision: 1, updated_at: 1};
const catalog = (subscriptions: WebhookSubscription[] = []) => ({subscriptions, listener: 'not_observed_running', credential_status: 'not_observed', transport: 'existing_shared_secret_required', admission: 'per_delivery_task_approval', remote_sender_authority: 'not_verified'});
const agents = [{id: 'owned-bot', name: 'Owned bot'}] as Agent[];
const fill = async (element: HTMLElement, label: string, value: string) => {
 const input = element.querySelector<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>(`[aria-label="${label}"]`)!;
 await act(async () => {Object.getOwnPropertyDescriptor(input instanceof HTMLInputElement ? HTMLInputElement.prototype : input instanceof HTMLSelectElement ? HTMLSelectElement.prototype : HTMLTextAreaElement.prototype, 'value')!.set!.call(input, value); input.dispatchEvent(new Event(input instanceof HTMLSelectElement ? 'change' : 'input', {bubbles: true}));});
};
it('creates a disabled definition with authoritative home binding, without ingress or credentials', async () => {
 const save = vi.fn(async (id, body) => ({scope: 'webhook.subscription', ok: true, operation_id: body.operation_id, subscription: {...body.definition, id, revision: 1, agent_id: 'owned-bot'}}));
 const source = {webhooks: {list: async () => catalog(), save}, agentHome: vi.fn(async () => ({agent_id: 'owned-bot', session_id: 'home-owned'}))} as unknown as JaegerSource;
 const element = document.createElement('div'); document.body.append(element); const root = createRoot(element);
 await act(async () => root.render(<WebhooksPanel source={source} agents={agents}/>));
 const button = (text: string) => [...element.querySelectorAll('button')].find(b => b.textContent === text)!;
 await act(async () => button('New disabled subscription').click());
 await fill(element, 'Webhook name', def.name); await fill(element, 'Webhook bot', 'owned-bot'); await fill(element, 'Webhook event filters', 'changed'); await fill(element, 'Webhook sender filters', 'owner-fixture'); await fill(element, 'Webhook objective', def.objective);
 await act(async () => button('Save disabled subscription').click());
 expect(save).toHaveBeenCalledOnce();
 expect(save.mock.calls[0][1]).toEqual({operation_id: expect.any(String), expected_revision: 0, definition: def});
 expect(source.agentHome).toHaveBeenCalledExactlyOnceWith('owned-bot');
 expect(element.textContent).toContain('No task was approved or external connection started');
 expect(element.querySelector('[type="password"]')).toBeNull();
 await act(async () => root.unmount()); element.remove();
});
it('retains unknown command and concrete binding across reload; reconciliation never resends', async () => {
 const save = vi.fn(async () => {throw Error('Response lost');});
 const operation = vi.fn(async () => ({receipt: null}));
 const source = {webhooks: {list: async () => catalog([row]), save, operation}} as unknown as JaegerSource;
 const element = document.createElement('div'); document.body.append(element); let root = createRoot(element);
 const render = () => <WebhooksPanel source={source} agents={agents}/>;
 await act(async () => root.render(render()));
 const button = (text: string) => [...element.querySelectorAll('button')].find(b => b.textContent === text)!;
 await act(async () => button('Enable proposals…').click());
 expect(save).not.toHaveBeenCalled();
 await act(async () => button('Confirm subscription state').click());
 expect(save).toHaveBeenCalledOnce();
 const key = Object.keys(localStorage).find(k => k.startsWith(prefix + 'command.v1.'))!;
 const intent = JSON.parse(localStorage.getItem(key)!);
 expect(intent.definition.session_id).toBe('home-owned');
 expect(intent.definition.enabled).toBe(true);
 await act(async () => root.unmount()); root = createRoot(element); await act(async () => root.render(render()));
 await act(async () => button('Check saved webhook command').click());
 expect(operation).toHaveBeenCalledExactlyOnceWith(intent.operationId);
 expect(save).toHaveBeenCalledOnce(); expect(localStorage.getItem(key)).not.toBeNull();
 expect(element.textContent).toContain('remains unknown');
 await act(async () => root.unmount()); element.remove();
});
it('shows redacted receipt status and retained unknown without replay or event-private data', async () => {
 const save = vi.fn();
 const source = {webhooks: {list: async () => catalog([row]), save, history: async () => ({subscription_id: row.id, deliveries: [{delivery_id: 'opaque-delivery', status: 'awaiting_approval', task_id: 'owned-task', task_state: 'paused', request_status: 'execution_unknown'}]})}} as unknown as JaegerSource;
 const element = document.createElement('div'); document.body.append(element); const root = createRoot(element);
 await act(async () => root.render(<WebhooksPanel source={source} agents={agents}/>));
 await act(async () => [...element.querySelectorAll('button')].find(b => b.textContent === 'Delivery receipts')!.click());
 expect(element.textContent).toContain('opaque-delivery'); expect(element.textContent).toContain('do not replay this event');
 expect(save).not.toHaveBeenCalled();
 await act(async () => root.unmount()); element.remove();
});
