#!/usr/bin/env node
// Generates src/shell/feels.css from tokens/jaeger-tokens.json (designer's approved tokens, 2026-10-31).
// House "jaeger" feel = Jaeger Blue accent family; other feels override the palette. Run: node scripts/gen-feels.mjs
import { readFileSync, writeFileSync } from "node:fs";
const t = JSON.parse(readFileSync(new URL("../tokens/jaeger-tokens.json", import.meta.url)));
const MAP = { surface: "--jg-color-pane", sidebar: "--jg-color-sidebar", raised: "--jg-color-elevated", inset: "--jg-color-inset", text: "--jg-color-text",
  "text-2": "--jg-color-text-secondary", "text-3": "--jg-color-text-tertiary", border: "--jg-color-border", accent: "--jg-color-accent", "accent-text": "--jg-color-accent-text",
  "on-accent": "--jg-color-on-accent", ok: "--jg-ok", warn: "--jg-warn", error: "--jg-bad", bg: "--jg-color-chrome" };
const BASE = ["accent", "accent-text", "on-accent"]; // house feel: only the Jaeger Blue accent family
const decls = (o, keys) => Object.entries(o).filter(([k, v]) => MAP[k] && v?.$value && (!keys || keys.includes(k))).map(([k, v]) => `  ${MAP[k]}: ${v.$value};`).join("\n");
const sel = (feel, mode) => feel === "jaeger"
  ? (mode === "light" ? ":root.aether-light-theme, :root[data-feel=\"jaeger\"].aether-light-theme" : ":root:not(.aether-light-theme), :root[data-feel=\"jaeger\"]:not(.aether-light-theme)")
  : `:root[data-feel="${feel}"]${mode === "light" ? ".aether-light-theme" : ":not(.aether-light-theme)"}`;
let out = "/* GENERATED by scripts/gen-feels.mjs from tokens/jaeger-tokens.json. Do not edit by hand. */\n";
for (const mode of ["light", "dark"]) out += `${sel("jaeger", mode)} {\n${decls(t.color[mode], BASE)}\n}\n`;
for (const [feel, v] of Object.entries(t.feel)) {
  if (feel === "jaeger" || !v || typeof v !== "object") continue;
  for (const mode of ["light", "dark"]) if (v[mode] && Object.keys(v[mode]).length) out += `${sel(feel, mode)} {\n${decls(v[mode])}\n}\n`;
}
// Live 64px previews in Settings › Appearance › Feel (each feel's own tokens, both modes).
for (const [feel, v] of Object.entries(t.feel)) {
  for (const mode of ["light", "dark"]) {
    const p = { ...t.color[mode], ...((v && v[mode]) || {}) };
    const scope = mode === "light" ? ":root.aether-light-theme" : ":root:not(.aether-light-theme)";
    out += `${scope} [data-feel-preview="${feel}"] {\n  --pv-bg: ${p.surface.$value};\n  --pv-side: ${p.sidebar.$value};\n  --pv-accent: ${p.accent.$value};\n  --pv-text: ${p.text.$value};\n}\n`;
  }
}
writeFileSync(new URL("../src/shell/feels.css", import.meta.url), out);
console.log("feels.css:", Object.keys(t.feel).join(", "));
